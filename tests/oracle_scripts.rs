//! Oracle DDL scripts as found in the wild: SQL*Plus commands, storage clauses, PL/SQL units,
//! sequences, views and computed columns. All names here are made up.

use sql_sage::dialect::DialectKind::{self, *};
use sql_sage::schema::Schema;
use sql_sage::{check_syntax, transpile};

fn derive(kind: DialectKind, sql: &str) -> String {
    let mut s = Schema::new(kind);
    let applied = s.apply_sql(sql).unwrap_or_else(|e| panic!("{sql}: {e}"));
    assert!(applied.errors.is_empty() && applied.skipped.is_empty(), "{sql}: {applied:?}");
    s.to_sql(kind).unwrap()
}

fn errors(kind: DialectKind, sql: &str) -> Vec<String> {
    let mut s = Schema::new(kind);
    let applied = s.apply_sql(sql).unwrap();
    assert!(applied.skipped.is_empty(), "{sql}: {:?}", applied.skipped);
    applied.errors.into_iter().map(|e| e.message).collect()
}

const SCRIPT: &str = "\u{feff}-- generated script
SET SQLBLANKLINES ON
;
WHENEVER SQLERROR EXIT 1

CREATE SEQUENCE order_seq
START WITH 1
INCREMENT BY 1
MINVALUE 0
NOCACHE;

CREATE TABLE orders (
  id        VARCHAR2(32 CHAR) NOT NULL,
  kind      NVARCHAR2(10) DEFAULT N'x' NOT NULL ENABLE,
  total     NUMBER(10, 2),
  online    NUMBER(1, 0) NOT NULL,
  CONSTRAINT pk_orders PRIMARY KEY (id) USING INDEX (CREATE UNIQUE INDEX pk_orders_ix ON orders (id) LOGGING),
  CONSTRAINT ck_total CHECK (total >= 0) ENABLE NOVALIDATE
)
 ROW STORE COMPRESS ADVANCED;

CREATE INDEX ix_orders_kind ON orders (kind, total) COMPRESS ADVANCED LOW;
CREATE UNIQUE INDEX ux_orders ON orders (id) TABLESPACE users PCTFREE 10 LOGGING;

CREATE GLOBAL TEMPORARY TABLE tmp_orders (id NUMBER) ON COMMIT PRESERVE ROWS;

CREATE OR REPLACE FUNCTION f(x NUMBER) RETURN NUMBER IS
BEGIN
  RETURN x + 1;
END;
/

CREATE OR REPLACE FORCE VIEW open_orders AS
  SELECT id, total FROM orders WHERE total > 0 WITH READ ONLY;

BEGIN
  EXECUTE IMMEDIATE 'ALTER TABLE orders ADD note VARCHAR2(10)';
END;
/

ALTER TABLE orders ADD (note2 VARCHAR2(10 CHAR), flag NUMBER(1) DEFAULT 0 NOT NULL);
ALTER TABLE orders ADD rev VARCHAR2(100 CHAR) AS (SUBSTR(id, 0, 100));
ALTER TABLE orders MODIFY (total NUMBER(12, 2));
";

#[test]
fn script_with_sqlplus_commands_storage_clauses_and_plsql() {
    let mut s = Schema::new(Oracle);
    let applied = s.apply_sql(SCRIPT).unwrap();
    assert_eq!(applied.errors, vec![]);
    // The function and the anonymous block are not understood; nothing else is skipped.
    let skipped: Vec<_> = applied.skipped.iter().map(|e| e.location.clone().unwrap().line).collect();
    assert_eq!(skipped, [27, 36]);
    assert_eq!(
        s.to_sql(Oracle).unwrap(),
        "CREATE SEQUENCE order_seq START WITH 1 INCREMENT BY 1 MINVALUE 0 NOCACHE;\n\
         CREATE TABLE orders (id VARCHAR2(32 CHAR) NOT NULL, kind NVARCHAR2(10) DEFAULT 'x' NOT NULL, \
         total NUMBER(12, 2), online NUMBER(1, 0) NOT NULL, note2 VARCHAR2(10 CHAR), \
         flag NUMBER(1) DEFAULT 0 NOT NULL, rev VARCHAR2(100 CHAR) GENERATED ALWAYS AS (SUBSTR(id, 0, 100)), \
         CONSTRAINT pk_orders PRIMARY KEY (id), CONSTRAINT ck_total CHECK (total >= 0));\n\
         CREATE INDEX ix_orders_kind ON orders (kind, total);\n\
         CREATE UNIQUE INDEX ux_orders ON orders (id);\n\
         CREATE OR REPLACE FORCE VIEW open_orders AS SELECT id, total FROM orders WHERE total > 0;"
    );
}

#[test]
fn physical_clauses_are_oracle_only() {
    for sql in [
        "CREATE TABLE t (a NUMBER) TABLESPACE users PCTFREE 10 INITRANS 2 STORAGE (INITIAL 64K NEXT 1M) NOLOGGING",
        "CREATE TABLE t (a NUMBER) SEGMENT CREATION IMMEDIATE COMPRESS FOR OLTP PARALLEL 4 ENABLE ROW MOVEMENT",
        "CREATE TABLE t (a CLOB) LOB (a) STORE AS SECUREFILE (TABLESPACE users ENABLE STORAGE IN ROW)",
        "CREATE TABLE t (a NUMBER PRIMARY KEY USING INDEX TABLESPACE users, b NUMBER UNIQUE ENABLE)",
        "CREATE TABLE t (a NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 100))",
        "CREATE INDEX i ON t (a) REVERSE NOSORT PARALLEL",
        "ALTER TABLE t ADD CONSTRAINT fk FOREIGN KEY (a) REFERENCES u (id) DEFERRABLE INITIALLY DEFERRED",
        "DROP TABLE t CASCADE CONSTRAINTS PURGE",
    ] {
        assert!(check_syntax(Oracle, sql).is_ok(), "{sql}");
    }
    assert!(check_syntax(Postgres, "CREATE TABLE t (a int) TABLESPACE users").is_err());
    assert!(check_syntax(Postgres, "CREATE INDEX i ON t (a) COMPRESS").is_err());
    assert!(check_syntax(Oracle, "CREATE TABLE t (a NUMBER) FROBNICATE").is_err());
}

#[test]
fn national_strings_and_bom() {
    assert!(check_syntax(Oracle, "\u{feff}INSERT INTO t VALUES (N'abc', n'it''s')").is_ok());
    assert!(check_syntax(Postgres, "SELECT N'abc'").is_ok());
}

#[test]
fn sequences() {
    assert_eq!(
        derive(Postgres, "CREATE SEQUENCE s START WITH 5 INCREMENT BY -2 MINVALUE -10 NO MAXVALUE NO CYCLE CACHE 20"),
        "CREATE SEQUENCE s START WITH 5 INCREMENT BY -2 MINVALUE -10 NO MAXVALUE NO CYCLE CACHE 20;"
    );
    assert_eq!(
        transpile(Postgres, Oracle, "CREATE SEQUENCE s NO MAXVALUE NO CYCLE").unwrap(),
        "CREATE SEQUENCE s NOMAXVALUE NOCYCLE;"
    );
    assert!(transpile(Oracle, Postgres, "CREATE SEQUENCE s NOMINVALUE NOCACHE ORDER").is_err());
    assert!(transpile(Postgres, Sqlite, "CREATE SEQUENCE s").is_err());
    assert_eq!(errors(Postgres, "CREATE SEQUENCE s; CREATE SEQUENCE s;"), ["sequence s already exists"]);
    assert_eq!(errors(Postgres, "DROP SEQUENCE nope;"), ["sequence nope does not exist"]);
    assert_eq!(derive(Postgres, "CREATE SEQUENCE s; DROP SEQUENCE s;"), "");
}

#[test]
fn views_are_tracked_and_replaced() {
    assert_eq!(
        derive(
            Postgres,
            "CREATE TABLE t (a int);
             CREATE VIEW v AS SELECT a FROM t;
             CREATE OR REPLACE VIEW v (x) AS SELECT a FROM t WHERE a > 0;
             CREATE VIEW gone AS SELECT 1; DROP VIEW gone; DROP VIEW IF EXISTS never_existed;"
        ),
        "CREATE TABLE t (a INT);\nCREATE OR REPLACE VIEW v (x) AS SELECT a FROM t WHERE a > 0;"
    );
    assert_eq!(errors(Postgres, "CREATE VIEW v AS SELECT 1; CREATE VIEW v AS SELECT 2;"), ["view v already exists"]);
    assert!(transpile(Postgres, Sqlite, "CREATE OR REPLACE VIEW v AS SELECT 1").is_err());
    assert!(transpile(Oracle, Postgres, "CREATE OR REPLACE FORCE VIEW v AS SELECT 1 FROM dual").is_err());
}

#[test]
fn generated_columns() {
    assert_eq!(
        transpile(Oracle, Postgres, "CREATE TABLE t (a NUMBER, b NUMBER AS (a * 2) VIRTUAL)").unwrap(),
        "CREATE TABLE t (a NUMERIC, b NUMERIC GENERATED ALWAYS AS (a * 2) STORED);"
    );
    assert_eq!(
        transpile(Postgres, Sqlite, "CREATE TABLE t (a int, b int GENERATED ALWAYS AS (a * 2) STORED)").unwrap(),
        "CREATE TABLE t (a INT, b INT GENERATED ALWAYS AS (a * 2) STORED);"
    );
}

#[test]
fn unparseable_statements_are_skipped_not_fatal() {
    let mut s = Schema::new(Postgres);
    let applied = s
        .apply_sql(
            "CREATE TABLE a (x int);
             CREATE TABLE b (x int) FROBNICATE;
             CREATE MATERIALIZED VIEW m AS SELECT 1;
             CREATE TABLE c (x int);",
        )
        .unwrap();
    assert_eq!(applied.errors, vec![]);
    assert_eq!(applied.skipped.len(), 2);
    assert_eq!(applied.skipped[0].location.as_ref().unwrap().line, 2);
    assert_eq!(s.to_sql(Postgres).unwrap(), "CREATE TABLE a (x INT);\nCREATE TABLE c (x INT);");
}

#[test]
fn plsql_units_are_skipped_up_to_the_slash_line() {
    let mut s = Schema::new(Oracle);
    let applied = s
        .apply_sql(
            "CREATE TABLE a (x NUMBER);
             CREATE OR REPLACE PROCEDURE p IS
             BEGIN
               INSERT INTO a VALUES (1);
               COMMIT;
             END;
             /
             CREATE TABLE b (x NUMBER);",
        )
        .unwrap();
    assert_eq!(applied.skipped.len(), 1);
    assert_eq!(s.tables().len(), 2);
}
